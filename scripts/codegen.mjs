import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const url = new URL("../contracts/openapi.yaml", import.meta.url);
const contractText = await readFile(url, "utf8");
// JSON is a strict subset of YAML and allows the same file to be served as JSON.
const spec = JSON.parse(contractText);
const route = (method, path) => method.toUpperCase() + " " + path;
const goString = value => JSON.stringify(value);
const policies = [];
const clientPaths = {};
for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of ["get", "post", "put", "delete"]) {
    const op = item[method];
    if (!op) continue;
    if (!op["x-permiso"] || (op["x-permiso"] !== "publico" && !op["x-roles"]?.length)) {
      throw new Error("Operación sin política: " + op.operationId);
    }
    const roles = (op["x-roles"] ?? []).map(goString).join(", ");
    policies.push("\t" + goString(op.operationId) + ": {" + goString(route(method, path)) + ", " + goString(op["x-permiso"]) + ", []string{" + roles + "}},");
    clientPaths[op.operationId] = { method: method.toUpperCase(), path };
  }
}
const header = "// Code generated by pnpm codegen. DO NOT EDIT.\n";
const api = new URL("../apps/api/internal/api/", import.meta.url);
const web = new URL("../apps/web/src/types/", import.meta.url);
await writeFile(new URL("contract.gen.go", api), header + "package api\n\ntype Operation struct {\n\tPattern string\n\tPermission string\n\tRoles []string\n}\n\nvar Operations = map[string]Operation{\n" + policies.join("\n") + "\n}\n\nconst OpenAPI = " + goString(JSON.stringify(spec)) + "\n");
await writeFile(new URL("contract.gen.ts", web), header + astToString(await openapiTS(url)) + "\nexport const operations = " + JSON.stringify(clientPaths, null, 2) + ` as const

export function endpoint(name: keyof typeof operations, params: Record<string, string | number> = {}) {
  const operation = operations[name];
  const path = operation.path.replace(/\\{([^}]+)\\}/g, (_, key: string) => {
    const value = params[key];
    if (value === undefined) throw new Error("Falta el parámetro " + key);
    return encodeURIComponent(value);
  });
  return { path, method: operation.method };
}
`);
